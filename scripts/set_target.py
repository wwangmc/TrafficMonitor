#!/usr/bin/env python3
"""Set the exact injection filter and runtime guard before building a package."""
import argparse
import plistlib
import re
from pathlib import Path


def configure(project, bundle_id):
    if not re.fullmatch(r"[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+", bundle_id):
        raise ValueError("Bundle ID must be a dotted identifier without wildcards")
    plist_path = project / "TrafficMonitor.plist"
    header_path = project / "Sources" / "TMTarget.h"
    # Validate both paths before changing any project content.
    if not plist_path.is_file() or not header_path.is_file():
        raise ValueError("Missing TrafficMonitor.plist or Sources/TMTarget.h")
    plist = plistlib.dumps({"Filter": {"Bundles": [bundle_id]}}, sort_keys=False)
    header = ("// Generated by scripts/set_target.py; keep synchronized with TrafficMonitor.plist.\n"
              "#pragma once\n"
              f'#define TM_TARGET_BUNDLE_ID @"{bundle_id}"\n')
    plist_path.write_bytes(plist)
    with header_path.open("w", encoding="utf-8", newline="\n") as output:
        output.write(header)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("bundle_id")
    args = parser.parse_args()
    try:
        configure(Path(__file__).resolve().parents[1], args.bundle_id)
    except (ValueError, OSError) as exc:
        parser.error(str(exc))
    print(f"Configured exact target: {args.bundle_id}")
    print("Rebuild/reinstall the package, then cold-launch the target app.")


if __name__ == "__main__":
    main()
